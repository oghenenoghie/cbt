from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

SchoolRole = Literal["school_admin", "teacher", "student"]
AccountStatus = Literal["active", "disabled"]

# Each password costs ~50 ms of Argon2 hashing, so a full import stays around 10 seconds.
MAX_IMPORT_ROWS = 200


class UserCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    username: str = Field(min_length=1, max_length=100)
    display_name: str = Field(min_length=1, max_length=200)
    role: SchoolRole
    email: str | None = Field(default=None, max_length=320)
    # Optional: without one, the account can't sign in until an admin sets a password.
    password: str | None = Field(default=None, max_length=1024)


class UserUpdate(BaseModel):
    """Fields to change; omitted fields stay as they are."""

    model_config = ConfigDict(extra="forbid")

    display_name: str | None = Field(default=None, min_length=1, max_length=200)
    email: str | None = Field(default=None, max_length=320)
    role: SchoolRole | None = None
    status: AccountStatus | None = None
    # Exam coordinators approve exams (ADR 0003). Only staff accounts can be coordinators.
    is_exam_coordinator: bool | None = None


class PasswordReset(BaseModel):
    model_config = ConfigDict(extra="forbid")

    new_password: str = Field(min_length=1, max_length=1024)


class ImportRow(BaseModel):
    model_config = ConfigDict(extra="forbid")

    username: str = Field(min_length=1, max_length=100)
    display_name: str = Field(min_length=1, max_length=200)
    role: SchoolRole = "student"
    email: str | None = Field(default=None, max_length=320)
    password: str | None = Field(default=None, max_length=1024)


class ImportRequest(BaseModel):
    """Create many accounts at once. Nothing is created unless every row is valid."""

    model_config = ConfigDict(extra="forbid")

    users: list[ImportRow] = Field(min_length=1, max_length=MAX_IMPORT_ROWS)
    # Generate a password for each row that has none. Generated passwords appear once, in the
    # response, and are never stored in readable form.
    generate_passwords: bool = False


class UserOut(BaseModel):
    id: str
    username: str
    display_name: str
    email: str | None
    role: str
    status: str
    is_exam_coordinator: bool
    has_password: bool
    created_at: datetime


class UserList(BaseModel):
    users: list[UserOut]
    # Pass as `after` to get the next page; None on the last page.
    next_after: str | None


class ImportedUser(UserOut):
    # Only set for rows whose password was generated by this import.
    generated_password: str | None = None


class ImportResult(BaseModel):
    created: list[ImportedUser]
